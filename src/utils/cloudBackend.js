/**
 * Lấy cấu hình Supabase từ biến môi trường (.env) hoặc cài đặt Admin của Khoa
 */
export function getCloudConfig() {
  const envUrl =
    (typeof import.meta !== 'undefined' && import.meta.env?.VITE_SUPABASE_URL) ||
    DEFAULT_SUPABASE_URL;
  const envKey =
    (typeof import.meta !== 'undefined' && import.meta.env?.VITE_SUPABASE_ANON_KEY) ||
    DEFAULT_SUPABASE_PUBLISHABLE_KEY;

  try {
    const saved = localStorage.getItem(CLOUD_CONFIG_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      return {
        url: (parsed.url || envUrl || '').trim().replace(/\/+$/, ''),
        anonKey: (parsed.anonKey || envKey || '').trim()
      };
    }
  } catch {
    // ignore storage errors
  }

  return {
    url: envUrl.trim().replace(/\/+$/, ''),
    anonKey: envKey.trim()
  };
}

/**
 * Lưu cấu hình Supabase từ Bảng Quản Trị của Khoa
 */
export function saveCloudConfig({ url, anonKey }) {
  const clean = {
    url: (url || '').trim().replace(/\/+$/, ''),
    anonKey: (anonKey || '').trim()
  };
  try {
    localStorage.setItem(CLOUD_CONFIG_STORAGE_KEY, JSON.stringify(clean));
  } catch {
    // ignore
  }
  return clean;
}

export function isCloudConfigured() {
  const { url, anonKey } = getCloudConfig();
  return Boolean(url && anonKey && url.startsWith('https://'));
}

/**
 * Tạo chữ ký băm SHA-256 (64 hex chars) cho mỗi lượt giải đã xác thực
 * giúp PostgreSQL Trigger trên Server kiểm chứng tính toàn vẹn.
 */
export async function computeSolveProof({
  boardId,
  playerName,
  puzzleType,
  bestTime,
  scramble,
  cameraVerified
}) {
  const canonical = [
    CLOUD_PROOF_SALT,
    boardId || 'board_1',
    (playerName || '').trim().toLowerCase(),
    puzzleType || '3x3',
    Number(bestTime).toFixed(2),
    (scramble || '').trim(),
    cameraVerified ? 'CAM_OK' : 'NO_CAM'
  ].join('|');

  try {
    if (typeof crypto !== 'undefined' && crypto.subtle) {
      const encoder = new TextEncoder();
      const data = encoder.encode(canonical);
      const hashBuffer = await crypto.subtle.digest('SHA-256', data);
      const hashArray = Array.from(new Uint8Array(hashBuffer));
      return hashArray.map(b => b.toString(16).padStart(2, '0')).join('');
    }
  } catch {
    // fallback deterministic 64-char hex
  }

  let h1 = 0xdeadbeef ^ canonical.length;
  let h2 = 0x41c6ce57 ^ canonical.length;
  for (let i = 0; i < canonical.length; i++) {
    const ch = canonical.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  const baseHex =
    ((h1 >>> 0).toString(16).padStart(8, '0') +
      (h2 >>> 0).toString(16).padStart(8, '0')).repeat(4);
  return baseHex.slice(0, 64);
}

/**
 * Kiểm tra kết nối tới Supabase Project của Khoa
 */
export async function testCloudConnection(customUrl, customAnonKey) {
  const cfg = customUrl !== undefined
    ? { url: (customUrl || '').trim().replace(/\/+$/, ''), anonKey: (customAnonKey || '').trim() }
    : getCloudConfig();

  if (!cfg.url || !cfg.anonKey) {
    return { ok: false, reason: 'Chưa nhập Supabase URL hoặc Anon Key.' };
  }

  try {
    const res = await fetch(
      `${cfg.url}/rest/v1/rubik_leaderboards?select=id&limit=1`,
      {
        method: 'GET',
        headers: buildSupabaseHeaders(cfg.anonKey)
      }
    );

    if (res.ok) {
      return { ok: true, message: 'Kết nối Supabase Cloud & Bảng Kỷ Lục thành công!' };
    }

    const errText = await res.text();
    if (res.status === 404 || errText.includes('rubik_leaderboards')) {
      return {
        ok: false,
        needsSchema: true,
        reason: 'Đã kết nối tới Supabase nhưng chưa tạo bảng rubik_leaderboards. Hãy bấm nút "Copy SQL" bên dưới và chạy trong Supabase SQL Editor!'
      };
    }

    return {
      ok: false,
      reason: `Supabase trả về mã lỗi ${res.status}: ${errText.slice(0, 120)}`
    };
  } catch (err) {
    return {
      ok: false,
      reason: `Không thể kết nối tới Supabase URL (${err?.message || 'Lỗi mạng'}).`
    };
  }
}

/**
 * Tải danh sách kỷ lục từ Supabase Cloud theo board_id
 */
export async function fetchCloudLeaderboard(boardId = 'board_1') {
  if (!isCloudConfigured()) {
    return { ok: false, unconfigured: true, entries: [] };
  }

  // Chống bot spam tải bảng xếp hạng liên tục
  const rate = checkRateLimit('cloud_fetch_leaderboard', {
    maxHits: 12,
    windowMs: 30000,
    cooldownMs: 10000
  });
  if (!rate.allowed) {
    return { ok: false, rateLimited: true, reason: rate.reason, entries: [] };
  }

  const cleanBoardId = sanitizeText(boardId, 40, 'board_1');
  const { url, anonKey } = getCloudConfig();
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    const query = new URLSearchParams({
      select: 'id,board_id,player_name,player_email,puzzle_type,best_time,avg_time,scramble,camera_verified,updated_at',
      board_id: `eq.${cleanBoardId}`,
      order: 'best_time.asc',
      limit: '100'
    });

    const res = await fetch(`${url}/rest/v1/rubik_leaderboards?${query.toString()}`, {
      method: 'GET',
      headers: buildSupabaseHeaders(anonKey),
      signal: controller.signal
    });
    clearTimeout(timeoutId);

    if (!res.ok) {
      return { ok: false, entries: [], status: res.status };
    }

    const rows = await res.json();
    const entries = (Array.isArray(rows) ? rows : []).map(r => ({
      id: r.id || `${r.player_name}_${r.puzzle_type}`,
      cloudId: r.id,
      puzzleType: sanitizeText(r.puzzle_type || '3x3', 10, '3x3'),
      name: sanitizeText(r.player_name, 40, 'Người chơi'),
      email: sanitizeEmail(r.player_email || '', ''),
      best: parseFloat(Number(r.best_time).toFixed(2)),
      avg: parseFloat(Number(r.avg_time).toFixed(2)),
      verified: Boolean(r.camera_verified),
      cloudSynced: true,
      date: r.updated_at
        ? new Date(r.updated_at).toLocaleDateString('vi-VN')
        : new Date().toLocaleDateString('vi-VN')
    }));

    return { ok: true, entries };
  } catch (err) {
    clearTimeout(timeoutId);
    return { ok: false, entries: [], error: err?.message };
  }
}

/**
 * Gửi lượt giải đã xác thực Camera AI + Anti-Bot lên Supabase Cloud
 */
export async function submitVerifiedSolveToCloud({
  boardId = 'board_1',
  playerName,
  playerEmail = 'guest@cuber.vn',
  puzzleType = '3x3',
  bestTime,
  avgTime,
  scramble,
  cameraVerified,
  startedScrambled = true
}) {
  if (!cameraVerified) {
    return { ok: false, reason: 'Chưa xác thực Camera AI' };
  }

  // Kiểm tra nguồn độc hại trong dữ liệu gửi đi
  if (hasMaliciousPayload(playerName) || hasMaliciousPayload(scramble) || hasMaliciousPayload(boardId)) {
    recordBlockedThreat('payload', 'Chặn dữ liệu chứa mã độc trước khi gửi lên Cloud');
    return { ok: false, reason: 'Phát hiện ký tự không an toàn trong dữ liệu gửi đi.' };
  }

  // Giới hạn tần suất gửi kỷ lục lên Cloud (tối đa 5 lần / phút)
  const rate = checkRateLimit('cloud_submit_solve', {
    maxHits: 5,
    windowMs: 60000,
    cooldownMs: 30000
  });
  if (!rate.allowed) {
    return { ok: false, rateLimited: true, reason: rate.reason };
  }

  const cleanBoardId = sanitizeText(boardId, 40, 'board_1');
  const cleanName = sanitizeText(playerName, 40, 'Người chơi');
  const cleanEmail = sanitizeEmail(playerEmail, 'guest@cuber.vn');
  const cleanScramble = sanitizeText(scramble, 320, 'WCA Verified Scramble');

  const proofHash = await computeSolveProof({
    boardId: cleanBoardId,
    playerName: cleanName,
    puzzleType,
    bestTime,
    scramble: cleanScramble,
    cameraVerified
  });

  if (!isCloudConfigured()) {
    return { ok: false, unconfigured: true, proofHash };
  }

  const { url, anonKey } = getCloudConfig();
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    const payload = {
      board_id: cleanBoardId,
      player_name: cleanName,
      player_email: cleanEmail,
      puzzle_type: puzzleType,
      best_time: Number(bestTime.toFixed(2)),
      avg_time: Number((avgTime || bestTime).toFixed(2)),
      scramble: cleanScramble,
      camera_verified: true,
      started_scrambled: Boolean(startedScrambled),
      proof_hash: proofHash
    };

    const res = await fetch(
      `${url}/rest/v1/rubik_leaderboards?on_conflict=board_id,player_name,puzzle_type`,
      {
        method: 'POST',
        headers: buildSupabaseHeaders(anonKey, {
          'Content-Type': 'application/json',
          Prefer: 'resolution=merge-duplicates,return=representation'
        }),
        body: JSON.stringify(payload),
        signal: controller.signal
      }
    );
    clearTimeout(timeoutId);

    if (!res.ok) {
      const errText = await res.text();
      return { ok: false, reason: errText, proofHash };
    }

    const data = await res.json();
    return { ok: true, data, proofHash };
  } catch (err) {
    clearTimeout(timeoutId);
    return { ok: false, reason: err?.message, proofHash };
  }
}

