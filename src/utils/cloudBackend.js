export function buildSupabaseHeaders(apiKey, extra = {}) {
  const key = (apiKey || '').trim();
  const headers = {
    apikey: key,
    ...extra
  };
  // Nếu là JWT (eyJ...) thì gửi kèm Authorization Bearer; với sb_publishable_... chỉ cần header apikey
  if (key.startsWith('eyJ')) {
    headers.Authorization = `Bearer ${key}`;
  }
  return headers;
}

