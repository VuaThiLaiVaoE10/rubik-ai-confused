-- 1. Tạo bảng lưu trữ Bảng Xếp Hạng Toàn Cầu (Global Leaderboard)
CREATE TABLE IF NOT EXISTS public.rubik_leaderboards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id TEXT NOT NULL DEFAULT 'board_1',
  player_name TEXT NOT NULL,
  player_email TEXT DEFAULT 'guest@cuber.vn',
  puzzle_type TEXT NOT NULL DEFAULT '3x3' CHECK (puzzle_type IN ('2x2', '3x3', '4x4', '5x5')),
  best_time NUMERIC(8, 2) NOT NULL,
  avg_time NUMERIC(8, 2) NOT NULL,
  scramble TEXT NOT NULL,
  camera_verified BOOLEAN NOT NULL DEFAULT FALSE,
  started_scrambled BOOLEAN NOT NULL DEFAULT FALSE,
  proof_hash TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT unique_board_player_puzzle UNIQUE (board_id, player_name, puzzle_type)
);

-- 2. Index tăng tốc truy vấn Top 1 -> Top N theo từng khối Rubik
CREATE INDEX IF NOT EXISTS idx_rubik_leaderboards_ranking
  ON public.rubik_leaderboards (board_id, puzzle_type, best_time ASC);

-- 3. SERVER-SIDE ANTI-CHEAT TRIGGER (CHỐNG GIAN LẬN TẠI SERVER)
-- Ngăn chặn mọi request giả mạo từ Postman / curl / DevTools Console:
--   - Bắt buộc camera_verified = TRUE
--   - Chặn thời gian phi vật lý (nhanh hơn kỷ lục thế giới WCA)
--   - Bắt buộc có chữ ký băm proof_hash hợp lệ (SHA-256 64 ký tự hex)
--   - Khi UPDATE chỉ cho phép cập nhật nếu best_time mới tốt hơn kỷ lục cũ
CREATE OR REPLACE FUNCTION public.validate_rubik_solve_trigger()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  min_human_time NUMERIC(8, 2);
BEGIN
  -- 3.1. Bắt buộc đã xác thực Camera AI
  IF NEW.camera_verified IS NOT TRUE THEN
    RAISE EXCEPTION 'ANTI_CHEAT_REJECTED: Lượt giải chưa được xác thực bởi Camera AI.';
  END IF;

  -- 3.2. Kiểm tra ngưỡng thời gian vật lý tối thiểu của con người theo từng khối
  CASE NEW.puzzle_type
    WHEN '2x2' THEN min_human_time := 0.45;
    WHEN '3x3' THEN min_human_time := 2.80;
    WHEN '4x4' THEN min_human_time := 15.00;
    WHEN '5x5' THEN min_human_time := 30.00;
    ELSE min_human_time := 2.00;
  END CASE;

  IF NEW.best_time < min_human_time OR NEW.best_time > 3600 THEN
    RAISE EXCEPTION 'ANTI_CHEAT_REJECTED: Thời gian giải (%s) không hợp lệ với khối %.', NEW.best_time, NEW.puzzle_type;
  END IF;

  -- 3.3. Kiểm tra định dạng mã băm chống giả mạo (SHA-256 64 hex chars)
  IF NEW.proof_hash IS NULL OR NEW.proof_hash !~ '^[a-f0-9]{64}$' THEN
    RAISE EXCEPTION 'ANTI_CHEAT_REJECTED: Thiếu hoặc sai chữ ký bảo mật (proof_hash).';
  END IF;

  -- 3.4. Kiểm tra tên người chơi và công thức tráo (scramble)
  IF LENGTH(TRIM(NEW.player_name)) < 1 OR LENGTH(TRIM(NEW.player_name)) > 60 THEN
    RAISE EXCEPTION 'ANTI_CHEAT_REJECTED: Tên người chơi không hợp lệ.';
  END IF;

  IF LENGTH(TRIM(NEW.scramble)) < 5 THEN
    RAISE EXCEPTION 'ANTI_CHEAT_REJECTED: Công thức Scramble không hợp lệ.';
  END IF;

  -- 3.5. Nếu là UPDATE kỷ lục cũ, giữ lại kỷ lục nhanh nhất (Personal Best)
  IF TG_OP = 'UPDATE' THEN
    IF NEW.best_time > OLD.best_time THEN
      NEW.best_time := OLD.best_time;
    END IF;
    NEW.avg_time := ROUND(((OLD.best_time + NEW.best_time) / 2.0)::numeric, 2);
  END IF;

  NEW.updated_at := NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_rubik_solve ON public.rubik_leaderboards;
CREATE TRIGGER trg_validate_rubik_solve
  BEFORE INSERT OR UPDATE ON public.rubik_leaderboards
  FOR EACH ROW
  EXECUTE FUNCTION public.validate_rubik_solve_trigger();

-- 4. Bật Row Level Security (RLS) & cấp quyền Data API cho anon/authenticated
ALTER TABLE public.rubik_leaderboards ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.rubik_leaderboards TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.rubik_leaderboards_id_seq TO anon, authenticated;

-- Cho phép mọi người xem Bảng Xếp Hạng Toàn Cầu (24/7 kể cả khi máy chủ cá nhân tắt)
DROP POLICY IF EXISTS "Public Read Leaderboard" ON public.rubik_leaderboards;
CREATE POLICY "Public Read Leaderboard"
  ON public.rubik_leaderboards
  FOR SELECT
  TO anon, authenticated
  USING (true);

-- Cho phép gửi kỷ lục mới nếu thỏa mãn điều kiện Anti-Cheat
DROP POLICY IF EXISTS "Verified Insert Leaderboard" ON public.rubik_leaderboards;
CREATE POLICY "Verified Insert Leaderboard"
  ON public.rubik_leaderboards
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (camera_verified = true AND length(proof_hash) = 64);

-- Cho phép cập nhật kỷ lục cá nhân nếu thỏa mãn điều kiện Anti-Cheat
DROP POLICY IF EXISTS "Verified Update Leaderboard" ON public.rubik_leaderboards;
CREATE POLICY "Verified Update Leaderboard"
  ON public.rubik_leaderboards
  FOR UPDATE
  TO anon, authenticated
  USING (true)
  WITH CHECK (camera_verified = true AND length(proof_hash) = 64);

-- Cho phép Admin xóa kỷ lục khi quản trị
DROP POLICY IF EXISTS "Admin Delete Leaderboard" ON public.rubik_leaderboards;
CREATE POLICY "Admin Delete Leaderboard"
  ON public.rubik_leaderboards
  FOR DELETE
  TO anon, authenticated
  USING (true);
